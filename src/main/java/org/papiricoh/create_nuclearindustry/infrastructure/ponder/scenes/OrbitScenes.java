package org.papiricoh.create_nuclearindustry.infrastructure.ponder.scenes;

import com.simibubi.create.foundation.ponder.CreateSceneBuilder;
import net.createmod.catnip.math.Pointing;
import net.createmod.ponder.api.scene.SceneBuilder;
import net.createmod.ponder.api.scene.SceneBuildingUtil;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.phys.Vec3;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.GuidePonderText;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.PlantPonderText;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.PlantPonderText.Script;
import org.papiricoh.create_nuclearindustry.missile.orbit.OrbitRegistry;
import org.papiricoh.create_nuclearindustry.missile.silo.SiloRegistry;

/** Satellites, on the schematics generated by tools/structgen/ponder_orbit.py. */
public final class OrbitScenes {
    public static void groundStation(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.GROUND_STATION;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 7);
        scene.scaleSceneView(0.9f);
        BlockPos station = util.grid().at(2, 1, 2);
        BlockPos motor = util.grid().at(2, 0, 2);
        BlockPos table = util.grid().at(4, 1, 4);

        scene.showBasePlate();
        scene.idle(10);
        scene.world().showSection(util.select().position(station), Direction.DOWN);
        scene.overlay().showText(100).text(lines.next()).pointAt(util.vector().topOf(station)).placeNearTarget().attachKeyFrame();
        scene.idle(30);
        scene.world().setKineticSpeed(util.select().position(motor), 32);
        scene.world().setKineticSpeed(util.select().position(station), 32);
        scene.effects().indicateSuccess(station);
        scene.idle(80);

        scene.overlay().showControls(util.vector().blockSurface(station, Direction.WEST), Pointing.RIGHT, 70).rightClick();
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().blockSurface(station, Direction.WEST)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(120);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(station).add(0, 0.5, 0)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(120);

        scene.world().showSection(util.select().fromTo(3, 1, 3, 5, 1, 5), Direction.DOWN);
        scene.idle(15);
        ItemStack linker = new ItemStack(SiloRegistry.TACTICAL_LINKER.get());
        scene.overlay().showControls(util.vector().topOf(station), Pointing.DOWN, 50).withItem(linker).rightClick();
        scene.idle(55);
        scene.overlay().showControls(util.vector().topOf(table), Pointing.DOWN, 50).withItem(linker).rightClick();
        scene.effects().indicateSuccess(station);
        scene.effects().indicateSuccess(table);
        scene.overlay().showText(120).text(lines.next()).pointAt(util.vector().topOf(table)).placeNearTarget().attachKeyFrame();
        scene.idle(130);
        scene.overlay().showText(100).text(lines.next()).pointAt(util.vector().topOf(station)).placeNearTarget().attachKeyFrame();
        scene.idle(110);
    }

    public static void satelliteLaunch(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.SATELLITE_LAUNCH;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 7);
        scene.scaleSceneView(0.55f);
        BlockPos controller = util.grid().at(5, 0, 3);
        BlockPos lever = util.grid().at(5, 1, 3);
        BlockPos engine = util.grid().at(3, 1, 3);
        BlockPos fairing = util.grid().at(3, 8, 3);
        BlockPos table = util.grid().at(2, 1, 7);
        BlockPos station = util.grid().at(5, 1, 7);

        scene.showBasePlate();
        scene.idle(10);
        scene.world().showSection(util.select().fromTo(2, 0, 2, 4, 0, 4), Direction.DOWN);
        scene.world().showSection(util.select().fromTo(5, 0, 3, 6, 0, 3), Direction.DOWN);
        scene.world().setKineticSpeed(util.select().fromTo(5, 0, 3, 6, 0, 3), 32);
        for (int y = 1; y <= 8; y++) {
            scene.world().showSection(util.select().position(3, y, 3), Direction.DOWN);
            scene.idle(10);
        }
        ItemStack satellite = new ItemStack(OrbitRegistry.COMMS_SATELLITE.get());
        scene.overlay().showControls(util.vector().blockSurface(fairing, Direction.WEST), Pointing.RIGHT, 70).withItem(satellite).rightClick();
        var incoming = scene.world().createItemEntity(util.vector().blockSurface(fairing, Direction.WEST).add(-0.8, 0, 0), new Vec3(0.1, 0, 0), satellite);
        scene.world().modifyEntity(incoming, entity -> entity.setNoGravity(true));
        scene.idle(8);
        scene.world().modifyEntity(incoming, Entity::discard);
        scene.effects().indicateSuccess(fairing);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(fairing)).placeNearTarget().attachKeyFrame();
        scene.idle(120);

        scene.overlay().showControls(util.vector().topOf(controller), Pointing.DOWN, 70).rightClick();
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(controller)).placeNearTarget().attachKeyFrame();
        scene.idle(120);

        scene.rotateCameraY(90);
        scene.idle(20);
        scene.world().showSection(util.select().position(lever), Direction.DOWN);
        scene.world().toggleRedstonePower(util.select().position(lever));
        scene.effects().indicateRedstone(lever);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().blockSurface(controller, Direction.EAST)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.world().toggleRedstonePower(util.select().position(lever));
        scene.rotateCameraY(-90);
        scene.idle(20);

        scene.world().showSection(util.select().fromTo(1, 0, 6, 3, 1, 8), Direction.DOWN);
        scene.world().showSection(util.select().fromTo(5, 0, 7, 5, 1, 7), Direction.DOWN);
        scene.world().setKineticSpeed(util.select().fromTo(5, 0, 7, 5, 1, 7), 32);
        scene.idle(15);
        ItemStack linker = new ItemStack(SiloRegistry.TACTICAL_LINKER.get());
        scene.overlay().showControls(util.vector().topOf(table), Pointing.DOWN, 70).withItem(linker).rightClick();
        scene.effects().indicateSuccess(controller);
        scene.effects().indicateSuccess(station);
        scene.effects().indicateSuccess(table);
        scene.overlay().showText(120).text(lines.next()).pointAt(util.vector().topOf(table)).placeNearTarget().attachKeyFrame();
        scene.idle(130);

        scene.world().hideSection(util.select().fromTo(3, 1, 3, 3, 8, 3), Direction.UP);
        scene.effects().emitParticles(util.vector().centerOf(engine),
                scene.effects().simpleParticleEmitter(ParticleTypes.LARGE_SMOKE, new Vec3(0, 0.25, 0)), 8, 25);
        scene.overlay().showText(120).text(lines.next()).pointAt(util.vector().topOf(3, 0, 3)).placeNearTarget().attachKeyFrame();
        scene.idle(130);
    }

    private OrbitScenes() {}
}
