package org.papiricoh.create_nuclearindustry.infrastructure.ponder.scenes;

import com.simibubi.create.foundation.ponder.CreateSceneBuilder;
import net.createmod.catnip.math.Pointing;
import net.createmod.ponder.api.PonderPalette;
import net.createmod.ponder.api.scene.SceneBuilder;
import net.createmod.ponder.api.scene.SceneBuildingUtil;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.phys.Vec3;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.GuidePonderText;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.PlantPonderText;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.PlantPonderText.Script;
import org.papiricoh.create_nuclearindustry.missile.defense.DefenseRegistry;
import org.papiricoh.create_nuclearindustry.missile.defense.battery.InterceptorBatteryEntity;
import org.papiricoh.create_nuclearindustry.missile.silo.SiloRegistry;

/** Missile defence, on the schematics generated by tools/structgen/ponder_defense.py. */
public final class DefenseScenes {
    public static void interceptorBattery(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.INTERCEPTOR_BATTERY;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 7);
        scene.scaleSceneView(0.8f);
        BlockPos battery = util.grid().at(2, 2, 2);
        BlockPos shaft = util.grid().at(2, 1, 2);
        BlockPos funnel = util.grid().at(1, 2, 2);
        BlockPos radar = util.grid().at(5, 1, 4);
        BlockPos lever = util.grid().at(1, 2, 3);
        BlockPos comparator = util.grid().at(3, 2, 1);

        scene.showBasePlate();
        scene.idle(10);
        // Reveal the complete multiblock without replacing its master: its BE draws the turret.
        scene.world().showSection(util.select().fromTo(2, 2, 2, 3, 3, 3), Direction.DOWN);
        scene.overlay().showControls(util.vector().blockSurface(battery, Direction.WEST), Pointing.RIGHT, 70)
                .withItem(new ItemStack(DefenseRegistry.BATTERY_ITEM.get())).rightClick();
        scene.overlay().showText(100).text(lines.next()).pointAt(util.vector().topOf(battery)).placeNearTarget().attachKeyFrame();
        scene.idle(110);

        scene.world().showSection(util.select().position(shaft), Direction.DOWN);
        scene.world().setKineticSpeed(util.select().fromTo(2, 0, 2, 2, 2, 2), 32);
        scene.overlay().showText(100).text(lines.next()).pointAt(util.vector().blockSurface(shaft, Direction.WEST)).placeNearTarget().attachKeyFrame();
        scene.idle(110);

        scene.world().showSection(util.select().position(funnel), Direction.EAST);
        ItemStack round = new ItemStack(DefenseRegistry.INTERCEPTOR.get());
        scene.overlay().showControls(util.vector().blockSurface(battery, Direction.NORTH), Pointing.RIGHT, 70)
                .withItem(round).rightClick();
        var incoming = scene.world().createItemEntity(util.vector().centerOf(funnel).add(-0.6, 0.1, 0),
                new Vec3(0.12, 0, 0), round);
        scene.world().modifyEntity(incoming, entity -> entity.setNoGravity(true));
        scene.idle(8);
        scene.world().modifyEntity(incoming, Entity::discard);
        scene.world().modifyBlockEntity(battery, InterceptorBatteryEntity.class,
                entity -> entity.loadOne(new ItemStack(DefenseRegistry.INTERCEPTOR.get())));
        scene.effects().indicateSuccess(battery);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().blockSurface(funnel, Direction.WEST)).placeNearTarget().attachKeyFrame();
        scene.idle(120);

        scene.world().showSection(util.select().position(radar), Direction.DOWN);
        scene.world().setKineticSpeed(util.select().position(radar), 32);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(radar)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.overlay().showControls(util.vector().blockSurface(battery, Direction.NORTH), Pointing.RIGHT, 70).rightClick();
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(battery)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.rotateCameraY(-25);
        scene.idle(20);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(battery)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.rotateCameraY(25);
        scene.idle(20);

        scene.world().showSection(util.select().position(lever), Direction.EAST);
        scene.world().toggleRedstonePower(util.select().position(lever));
        scene.effects().indicateRedstone(lever);
        scene.overlay().showText(100).text(lines.next()).colored(PonderPalette.RED)
                .pointAt(util.vector().blockSurface(lever, Direction.WEST)).placeNearTarget().attachKeyFrame();
        scene.idle(110);
        scene.world().toggleRedstonePower(util.select().position(lever));
        scene.world().showSection(util.select().fromTo(3, 1, 1, 3, 2, 1), Direction.DOWN);
        scene.overlay().showText(100).text(lines.next()).pointAt(util.vector().topOf(comparator)).placeNearTarget().attachKeyFrame();
        scene.idle(110);
    }

    public static void interceptorSilo(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.INTERCEPTOR_SILO;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 7);
        scene.scaleSceneView(0.65f);
        BlockPos controller = util.grid().at(5, 0, 3);
        BlockPos lever = util.grid().at(5, 1, 3);
        BlockPos engine = util.grid().at(3, 1, 3);
        BlockPos vehicle = util.grid().at(3, 6, 3);
        BlockPos table = util.grid().at(2, 1, 7);

        scene.showBasePlate();
        scene.idle(10);
        scene.world().showSection(util.select().fromTo(2, 0, 2, 4, 0, 4), Direction.DOWN);
        scene.world().showSection(util.select().fromTo(5, 0, 3, 6, 0, 3), Direction.DOWN);
        scene.world().showSection(util.select().fromTo(3, 0, 0, 3, 0, 1), Direction.DOWN);
        scene.world().setKineticSpeed(util.select().fromTo(5, 0, 3, 6, 0, 3), 32);
        for (int y = 1; y <= 6; y++) {
            scene.world().showSection(util.select().position(3, y, 3), Direction.DOWN);
            scene.idle(15);
        }
        scene.overlay().showControls(util.vector().topOf(vehicle), Pointing.DOWN, 70)
                .withItem(new ItemStack(SiloRegistry.KILL_VEHICLE.get()));
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(vehicle)).placeNearTarget().attachKeyFrame();
        scene.idle(120);

        scene.rotateCameraY(90);
        scene.idle(20);
        scene.world().showSection(util.select().position(lever), Direction.DOWN);
        scene.world().toggleRedstonePower(util.select().position(lever));
        scene.effects().indicateRedstone(lever);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().blockSurface(controller, Direction.EAST)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.world().toggleRedstonePower(util.select().position(lever));
        scene.rotateCameraY(-90);
        scene.idle(20);

        scene.world().showSection(util.select().fromTo(1, 0, 6, 3, 1, 8), Direction.DOWN);
        scene.overlay().showControls(util.vector().topOf(controller), Pointing.DOWN, 70)
                .withItem(new ItemStack(SiloRegistry.TACTICAL_LINKER.get())).rightClick();
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(table)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.overlay().showControls(util.vector().topOf(table), Pointing.DOWN, 70)
                .withItem(new ItemStack(SiloRegistry.TACTICAL_LINKER.get())).rightClick();
        scene.effects().indicateSuccess(controller);
        scene.effects().indicateSuccess(table);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(table)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.overlay().showControls(util.vector().topOf(table), Pointing.DOWN, 70).rightClick();
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(table)).placeNearTarget().attachKeyFrame();
        scene.idle(120);

        scene.world().hideSection(util.select().fromTo(3, 1, 3, 3, 6, 3), Direction.UP);
        scene.effects().emitParticles(util.vector().centerOf(engine),
                scene.effects().simpleParticleEmitter(ParticleTypes.LARGE_SMOKE, new Vec3(0, 0.25, 0)), 8, 25);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(3, 0, 3)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
    }

    private DefenseScenes() {}
}
