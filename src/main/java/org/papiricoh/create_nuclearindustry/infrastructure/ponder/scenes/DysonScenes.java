package org.papiricoh.create_nuclearindustry.infrastructure.ponder.scenes;

import com.simibubi.create.foundation.ponder.CreateSceneBuilder;
import net.createmod.catnip.math.Pointing;
import net.createmod.ponder.api.scene.SceneBuilder;
import net.createmod.ponder.api.scene.SceneBuildingUtil;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.item.ItemStack;
import org.papiricoh.create_nuclearindustry.dyson.DysonRegistry;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.GuidePonderText;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.PlantPonderText;
import org.papiricoh.create_nuclearindustry.infrastructure.ponder.PlantPonderText.Script;

/** The Dyson swarm's machines, on the schematics generated by tools/structgen/ponder_dyson.py. */
public final class DysonScenes {
    private DysonScenes() {
    }

    public static void ejector(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.EM_RAIL_EJECTOR;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 7);
        scene.scaleSceneView(0.9f);
        BlockPos ejector = util.grid().at(3, 1, 3);
        BlockPos motor = util.grid().at(3, 0, 3);
        BlockPos hopper = util.grid().at(3, 1, 4);

        scene.showBasePlate();
        scene.idle(10);
        scene.world().showSection(util.select().position(ejector), Direction.DOWN);
        scene.idle(10);
        scene.world().setKineticSpeed(util.select().position(motor), 128);
        scene.world().setKineticSpeed(util.select().position(ejector), 128);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(ejector)).placeNearTarget().attachKeyFrame();
        scene.idle(120);

        scene.world().showSection(util.select().fromTo(3, 1, 4, 3, 2, 4), Direction.DOWN);
        scene.idle(10);
        ItemStack sails = new ItemStack(DysonRegistry.SOLAR_SAIL.get(), 16);
        scene.overlay().showControls(util.vector().blockSurface(ejector, Direction.WEST), Pointing.RIGHT, 60).withItem(sails).rightClick();
        scene.overlay().showText(90).text(lines.next()).pointAt(util.vector().topOf(hopper)).placeNearTarget().attachKeyFrame();
        scene.idle(100);

        scene.overlay().showText(130).text(lines.next()).pointAt(util.vector().topOf(ejector).add(0, 0.6, 0)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(60);
        scene.effects().indicateSuccess(ejector);
        scene.idle(80);

        scene.overlay().showControls(util.vector().blockSurface(ejector, Direction.WEST), Pointing.RIGHT, 70).rightClick();
        scene.overlay().showText(120).text(lines.next()).pointAt(util.vector().blockSurface(ejector, Direction.WEST)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(130);
    }

    public static void receivers(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.RAY_RECEIVER;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 7);
        scene.scaleSceneView(0.9f);
        BlockPos first = util.grid().at(1, 1, 3);
        BlockPos middle = util.grid().at(3, 1, 3);
        BlockPos last = util.grid().at(5, 1, 3);

        scene.showBasePlate();
        scene.idle(10);
        scene.world().showSection(util.select().position(middle), Direction.DOWN);
        scene.idle(10);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(middle)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.overlay().showText(120).text(lines.next()).pointAt(util.vector().topOf(middle).add(0, 0.5, 0)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(130);

        scene.world().showSection(util.select().position(first), Direction.DOWN);
        scene.world().showSection(util.select().position(last), Direction.DOWN);
        scene.idle(15);
        scene.effects().indicateSuccess(first);
        scene.effects().indicateSuccess(middle);
        scene.effects().indicateSuccess(last);
        scene.overlay().showText(140).text(lines.next()).pointAt(util.vector().topOf(last)).placeNearTarget().attachKeyFrame();
        scene.idle(150);
        scene.overlay().showText(90).text(lines.next()).pointAt(util.vector().topOf(first)).placeNearTarget().attachKeyFrame();
        scene.idle(100);
    }

    public static void terminal(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        PlantPonderText.Scene text = GuidePonderText.SWARM_TERMINAL;
        Script lines = text.script();
        scene.title(text.id(), text.title().english());
        scene.configureBasePlate(0, 0, 5);
        BlockPos terminal = util.grid().at(2, 1, 2);

        scene.showBasePlate();
        scene.idle(10);
        scene.world().showSection(util.select().position(terminal), Direction.DOWN);
        scene.idle(10);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().blockSurface(terminal, Direction.WEST)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(120);
        scene.overlay().showControls(util.vector().blockSurface(terminal, Direction.WEST), Pointing.RIGHT, 70).rightClick();
        scene.overlay().showText(130).text(lines.next()).pointAt(util.vector().blockSurface(terminal, Direction.WEST)).placeNearTarget()
                .attachKeyFrame();
        scene.idle(140);
        scene.overlay().showText(110).text(lines.next()).pointAt(util.vector().topOf(terminal)).placeNearTarget().attachKeyFrame();
        scene.idle(120);
        scene.overlay().showText(100).text(lines.next()).pointAt(util.vector().topOf(terminal)).placeNearTarget().attachKeyFrame();
        scene.idle(110);
    }
}
